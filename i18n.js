  let lang = "id";

  function detectBrowser() {
    const nav = (navigator.language || navigator.userLanguage || "id").toLowerCase();
    const code = nav.slice(0, 2);
    if (LANGUAGES.some((l) => l.code === code)) return code;
    return "id";
  }

  function load() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
    } catch (e) {}
    try {
      const old = localStorage.getItem("perjuangan_lang_v1");
      if (old === "id" || old === "en") return old;
    } catch (e) {}
    return detectBrowser();
  }

  function save() {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    if (PJ.Progress && typeof PJ.Progress.setLanguage === "function") {
      PJ.Progress.setLanguage(lang);
    }
  }

  function init() {
    lang = load();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }

  function t(key) {
    const pack = STR[lang] || STR.en;
    if (pack[key] != null) return pack[key];
    if (STR.en[key] != null) return STR.en[key];
    if (STR.id[key] != null) return STR.id[key];
    return key;
  }

  function getLang() {
    return lang;
  }

  function setLang(next) {
    if (!LANGUAGES.some((l) => l.code === next)) return;
    lang = next;
    save();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.dispatchEvent(new CustomEvent("pj:langchange", { detail: { lang } }));
  }

  function toggle() {
    setLang(lang === "id" ? "en" : "id");
  }

  function getLanguages() {
    return LANGUAGES.slice();
  }

  function getLanguageMeta(code) {
    return LANGUAGES.find((l) => l.code === code) || null;
  }

  init();

  return {
    t,
    getLang,
    setLang,
    toggle,
    getLanguages,
    getLanguageMeta,
    STR,
    LANGUAGES,
  };
